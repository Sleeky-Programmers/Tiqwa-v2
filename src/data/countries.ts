/** Emoji flag from an ISO-3166 alpha-2 code ("NG" → 🇳🇬). */
export const flag = (iso2: string) => String.fromCodePoint(...[...iso2.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));

